# выданный маршрут — снятие применяется только в момент выдачи, уже выданные
# заявки от него не зависят. Побочный эффект: в UI старые шаги выглядят
# необязательными, но снять их у сотрудника ОК нельзя — правка маршрута
# выданной заявки идёт через PATCH /requests/{id}/steps, а не через это поле.
