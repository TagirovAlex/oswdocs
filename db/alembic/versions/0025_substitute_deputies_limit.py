# настройкой — её правит администратор вместе с прочими инфраструктурными
# настройками (ключ в INFRA_KEYS, виден в GET/PUT /settings).
#
# Что означает 3 (значение сида): у одного сотрудника одновременно действует не
# больше трёх записей-заместителей. Считаются только действующие на сегодня записи
# (срок начался и ещё не кончился): законченные и ещё не начатые место не занимают,
# иначе истёкшие записи заблокировали бы новые навсегда. Проверка одна и та же для
# админских ручек /settings/substitutes и личных /substitutes/my — справочник один.
# Лимит проверяет api/app/substitutes.py (_deputies_limit); он же, если ключ по
# какой-то причине недоступен, работает по этому же значению (см. докстринг хелпера).
#
# Чего миграция НЕ делает: схему не меняет (settings уже есть), существующие записи
# не трогает — если у кого-то заместителей больше лимита, они остаются; править их
# админ будет сам (удалить лишние или поднять лимит настройкой).
#
# Вверх — сид значения (идемпотентно, по образцу 0022 timezone: у кого настройка
# уже заведена руками — не перетираем); вниз — удаление ключа.
