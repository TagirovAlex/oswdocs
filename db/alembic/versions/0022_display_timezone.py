# 2026-10-13 — «все даты и время в системе должны показываться в одной зоне,
# чтобы не убегало»).
#
# Что делает:
#   • заводит ключ settings.timezone — им приводятся все даты в интерфейсе
#     (/auth/me отдаёт его, фронт форматирует через Intl с этой зоной);
#   • значение сида — Europe/Moscow, тот же дефолт, что у переменной TZ
#     контейнеров в compose (api/worker/db/proxy/redis) и в .env.example.
#     При смене зоны админ правит настройку, а TZ в .env — чтобы имена бэкапов
#     и метки времени в логах не расходились с интерфейсом. Пустая настройка не
#     значит «зона браузера»: /auth/me отдаёт TZ контейнера.
#
# Чего миграция НЕ делает:
#   • не меняет схему (settings уже есть, новых колонок не нужно);
#   • не переводит уже записанные метки времени: они хранятся в TIMESTAMPTZ,
#     приведение к зоне — дело отображения.
#
# Почему отображение, а не запись: API отдаёт метки с их настоящим смещением
# (сессия Postgres в Etc/UTC — отсюда +00:00), и приводить их к зоне на
# стороне интерфейса правильнее, чем подменять смещение в ответе: хранимое
# остаётся UTC, показываемое — локальное время компании.
